// Embeds D1 migrations and the question seed into the Worker bundle (src/generated/d1-bootstrap.ts),
// so a fresh database is set up on first request without running wrangler by hand.
// Runs before every `next build`; the output is committed so typecheck works without a build.
import { createHash } from "crypto";
import { readdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import { questionSeedStatements } from "./question-seed";

const dir = "prisma/migrations-d1";

/** Prisma emits one statement per ";"-terminated block; comment lines are dropped. */
function splitSql(sql: string) {
  return sql
    .split("\n")
    .filter((l) => !l.trim().startsWith("--"))
    .join("\n")
    .split(/;\s*(?:\n|$)/)
    .map((s) => s.trim())
    .filter(Boolean);
}

const migrations = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((name) => ({ name, statements: splitSql(readFileSync(path.join(dir, name), "utf8")) }));

const seed = questionSeedStatements();
// Name changes with the catalogue, so edited questions are re-applied once.
const seedName = `seed-questions-${createHash("sha256").update(seed.join("\n")).digest("hex").slice(0, 12)}`;

const steps = [...migrations, { name: seedName, statements: seed }];
const out = "src/generated/d1-bootstrap.ts";
writeFileSync(
  out,
  `// Generated by scripts/gen-d1-bootstrap.ts — do not edit.\n` +
    `export const D1_BOOTSTRAP_STEPS: { name: string; statements: string[] }[] = ${JSON.stringify(steps, null, 2)};\n`,
);
console.log(`✓ ${migrations.length} migration(s) + ${seed.length} questions → ${out}`);
